<?php

declare(strict_types=1);

namespace Ls\Omni\Test\Unit\Model\VendorSourcing;

use Ls\Omni\Client\CentralEcommerce\Entity\InventoryBufferOut;
use Ls\Omni\Client\CentralEcommerce\Entity\RootGetInventoryMultipleOut;
use Ls\Omni\Model\VendorSourcing\ZeroStockEverywhereResolver;
use PHPUnit\Framework\TestCase;
use ReflectionClass;

/**
 * Unit tests for {@see ZeroStockEverywhereResolver} (ticket 89360, solution plan §6.1/§12).
 *
 * This is a pure, dependency-free classifier: given an all-store aggregate
 * GetInventoryMultipleV2 response (StockHelper::getGivenItemsStockInGivenStore() called with no
 * store id - one buffer row per (item, variant, store) combination across every store, solution
 * plan §2.7) and the StockHelper::mergeStockCollection()-shaped rows being checked, it answers
 * "does ANY store carry enough stock of this row" - true meaning stock exists somewhere (NOT
 * zero-stock-everywhere), false meaning zero-stock-everywhere is confirmed.
 *
 * RootGetInventoryMultipleOut/InventoryBufferOut are autogenerated entities extending
 * \Magento\Catalog\Model\AbstractModel - following the ItemHelperTest/BasketHelperTest precedent,
 * they are built via ReflectionClass::newInstanceWithoutConstructor() + setData()-backed setters,
 * which works safely without the constructor running.
 */
class ZeroStockEverywhereResolverTest extends TestCase
{
    private ZeroStockEverywhereResolver $resolver;

    protected function setUp(): void
    {
        $this->resolver = new ZeroStockEverywhereResolver();
    }

    /**
     * @param string $number
     * @param string $variant
     * @param string $store
     * @param float $inventory
     * @return InventoryBufferOut
     */
    private function createBufferRow(string $number, string $variant, string $store, float $inventory): InventoryBufferOut
    {
        /** @var InventoryBufferOut $row */
        $row = (new ReflectionClass(InventoryBufferOut::class))->newInstanceWithoutConstructor();
        $row->setNumber($number)->setVariant($variant)->setStore($store)->setInventory($inventory);

        return $row;
    }

    /**
     * @param InventoryBufferOut[] $bufferRows
     * @return RootGetInventoryMultipleOut
     */
    private function createResponse(array $bufferRows): RootGetInventoryMultipleOut
    {
        /** @var RootGetInventoryMultipleOut $response */
        $response = (new ReflectionClass(RootGetInventoryMultipleOut::class))->newInstanceWithoutConstructor();
        $response->setInventorybufferout($bufferRows);

        return $response;
    }

    /**
     * One store (of several) has enough inventory to satisfy the requested qty - the row must
     * be classified as NOT zero-stock-everywhere (true).
     */
    public function testResolveReturnsTrueWhenOneStoreSatisfiesQty(): void
    {
        $response = $this->createResponse([
            $this->createBufferRow('ITEM1', 'VAR1', 'S1', 0.0),
            $this->createBufferRow('ITEM1', 'VAR1', 'S2', 5.0),
            $this->createBufferRow('ITEM1', 'VAR1', 'S3', 0.0),
        ]);

        $rows = [
            ['item_id' => 'ITEM1', 'variant_id' => 'VAR1', 'qty' => 2.0],
        ];

        $result = $this->resolver->resolve($response, $rows);

        $this->assertSame(['ITEM1|VAR1' => true], $result);
    }

    /**
     * No store across the whole response satisfies the requested qty - zero-stock-everywhere
     * is confirmed (false).
     */
    public function testResolveReturnsFalseWhenNoStoreSatisfiesQty(): void
    {
        $response = $this->createResponse([
            $this->createBufferRow('ITEM1', 'VAR1', 'S1', 0.0),
            $this->createBufferRow('ITEM1', 'VAR1', 'S2', 1.0),
        ]);

        $rows = [
            ['item_id' => 'ITEM1', 'variant_id' => 'VAR1', 'qty' => 2.0],
        ];

        $result = $this->resolver->resolve($response, $rows);

        $this->assertSame(['ITEM1|VAR1' => false], $result);
    }

    /**
     * A null response (e.g. Central call failed/returned no usable data) must classify every
     * row as zero-stock-everywhere (false), never throwing and never defaulting to true.
     */
    public function testResolveReturnsFalseForEveryRowWhenResponseIsNull(): void
    {
        $rows = [
            ['item_id' => 'ITEM1', 'variant_id' => 'VAR1', 'qty' => 1.0],
            ['item_id' => 'ITEM2', 'variant_id' => 'VAR2', 'qty' => 3.0],
        ];

        $result = $this->resolver->resolve(null, $rows);

        $this->assertSame(
            ['ITEM1|VAR1' => false, 'ITEM2|VAR2' => false],
            $result
        );
    }

    /**
     * A buffer row for a DIFFERENT item/variant combination, even with ample inventory, must not
     * satisfy an unrelated row's qty requirement - exact (item_id, variant_id) matching only.
     */
    public function testResolveDoesNotMatchUnrelatedItemOrVariant(): void
    {
        $response = $this->createResponse([
            $this->createBufferRow('ITEM2', 'VAR2', 'S1', 50.0),
            $this->createBufferRow('ITEM1', 'VAR9', 'S1', 50.0),
        ]);

        $rows = [
            ['item_id' => 'ITEM1', 'variant_id' => 'VAR1', 'qty' => 1.0],
        ];

        $result = $this->resolver->resolve($response, $rows);

        $this->assertSame(['ITEM1|VAR1' => false], $result);
    }
}
